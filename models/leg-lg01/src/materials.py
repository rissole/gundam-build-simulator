"""glTF-safe Principled materials. Hex inputs are sRGB; shader factors linear.

Wear is a very subtle per-corner RGB multiplier, exported as COLOR_0. Surface
roughness remains a constant PBR factor, avoiding unsupported procedural masks.
Decal textures are generated by system Python (make_decals.py), never Pillow
inside Blender. No normal maps or procedural-only material effects are used.
"""
from pathlib import Path
import bpy

DECALS = Path(__file__).resolve().parent / 'decals'
PALETTE = {
    'armor': ('Armor satin', '#D2C8BC', 0.0, .45),
    'gunmetal': ('Gunmetal', '#4C4C4B', .6, .5),
    'ochre': ('Safety ochre', '#D4861D', .05, .45),
    'red': ('Caution red', '#C2332A', 0.0, .48),
    'chrome': ('Polished rod chrome', '#C7D0D7', 1.0, .17),
    'bronze': ('Bronze nozzle lining', '#A77738', .8, .33),
    'rubber': ('Rubber', '#222421', 0.0, .82),
    'amber': ('Amber sensor', '#FFAC32', .15, .28),
    'steel': ('Fastener steel', '#72777A', .8, .36),
    'recess': ('Dark recess', '#222322', .15, .72),
}


def srgb_to_linear(value):
    return value/12.92 if value <= .04045 else ((value+.055)/1.055)**2.4


def hex_linear(value):
    return tuple(srgb_to_linear(int(value.lstrip('#')[i:i+2],16)/255) for i in (0,2,4))


def principled(name,hex_color,metallic=0,roughness=.45,wear=False):
    mat=bpy.data.materials.get(name) or bpy.data.materials.new(name)
    mat.use_nodes=True
    nodes=mat.node_tree.nodes
    nodes.clear()
    output=nodes.new('ShaderNodeOutputMaterial')
    bsdf=nodes.new('ShaderNodeBsdfPrincipled')
    color=(*hex_linear(hex_color),1)
    mat.diffuse_color=color
    bsdf.inputs['Base Color'].default_value=color
    bsdf.inputs['Metallic'].default_value=metallic
    bsdf.inputs['Roughness'].default_value=roughness
    mat.node_tree.links.new(bsdf.outputs['BSDF'],output.inputs['Surface'])
    if wear:
        attr=nodes.new('ShaderNodeVertexColor'); attr.layer_name='Wear'
        # Blender 5's glTF recognizer supports the current Mix Color node;
        # legacy MixRGB silently loses the constant paint factor on export.
        multiply=nodes.new('ShaderNodeMix'); multiply.data_type='RGBA'; multiply.blend_type='MULTIPLY'
        multiply.inputs[0].default_value=1
        multiply.inputs[6].default_value=color
        mat.node_tree.links.new(attr.outputs['Color'],multiply.inputs[7])
        mat.node_tree.links.new(multiply.outputs[2],bsdf.inputs['Base Color'])
    mat['palette_srgb']=hex_color
    mat['expected_base_color']=list(color)
    mat['expected_metallic']=metallic
    mat['expected_roughness']=roughness
    return mat


def create_materials():
    result={key:principled('LG01 '+name,color,metal,rough,key in {'armor','ochre'})
            for key,(name,color,metal,rough) in PALETTE.items()}
    node=result['amber'].node_tree.nodes.get('Principled BSDF')
    node.inputs['Emission Color'].default_value=(*hex_linear('#FFAC32'),1)
    node.inputs['Emission Strength'].default_value=2.0
    return result


def decal_material(kind='caution'):
    path=DECALS/(kind+'.png')
    if not path.exists():
        raise FileNotFoundError(f'Run system python3 {Path(__file__).with_name("make_decals.py")} first')
    mat=principled('LG01 Decal '+kind,'#FFFFFF',0,.5)
    bsdf=mat.node_tree.nodes.get('Principled BSDF')
    tex=mat.node_tree.nodes.new('ShaderNodeTexImage')
    tex.image=bpy.data.images.load(str(path),check_existing=True)
    tex.image.alpha_mode='STRAIGHT'
    mat.node_tree.links.new(tex.outputs['Color'],bsdf.inputs['Base Color'])
    mat.node_tree.links.new(tex.outputs['Alpha'],bsdf.inputs['Alpha'])
    mat.surface_render_method='DITHERED'
    mat.use_backface_culling=True
    return mat


def decal(kind='caution',width=.7,height=None,name=None):
    """Thin closed decal sheet (0.2 mm), front at local Z=0, with explicit UVs.

    Place ~0.5 mm above receiving armor. This is the only intentionally sheetlike
    kit feature; it still has real thickness. RGBA PNG -> Base Color and Alpha.
    """
    from kit import chamfered_box
    height=height or width*({'caution':.2,'unit01':.8,'red_marks':.3}[kind])
    obj=chamfered_box((width,height,.0002),(0,0,-.0001),0,decal_material(kind),
                      name or 'Stencil '+kind)
    uv=obj.data.uv_layers.new(name='UVMap')
    for face in obj.data.polygons:
        for i in face.loop_indices:
            co=obj.data.vertices[obj.data.loops[i].vertex_index].co
            uv.data[i].uv=(co.x/width+.5,co.y/height+.5)
    obj['decal_kind']=kind
    return obj
